-- Typed Neraca lines of book years 2025 and 2026. Lines already typed in the
-- app are kept.
-- 2025: Neraca posisi 31 Desember 2025 of the RAT report (CONTOH LAPORAN
-- KEUANGAN RAT, sheet Neraca, kolom TAHUN 2025).
-- 2026: NERACA of BUKU KAS HARIAN (kolom Januari 2026; Simpanan Non Anggota
-- from Desember 2025, as the January cell points at the wrong row). Cadangan
-- and dana are the RAT 2025 amounts less their use (NERACA PENYESUAIAN).
INSERT OR IGNORE INTO balance_sheet_items (company_id, year, item_key, amount)
SELECT id, year, item_key, amount
FROM companies, (
  SELECT 2025 year, 'OTHER_LOANS' item_key, 28109000 amount
  UNION ALL SELECT 2025, 'FIXED_ASSETS', 1
  UNION ALL SELECT 2025, 'DEBT_PPBRI', 10000000
  UNION ALL SELECT 2025, 'NON_MEMBER_SAVINGS', 876000
  UNION ALL SELECT 2025, 'CAPITAL_RESERVE', 42991150
  UNION ALL SELECT 2025, 'EDUCATION_FUND', 6460622
  UNION ALL SELECT 2025, 'SOCIAL_FUND', 4232995
  UNION ALL SELECT 2025, 'PMDK_FUND', 6494387
  UNION ALL SELECT 2025, 'RAT_RESERVE', 20000000
  UNION ALL SELECT 2025, 'LOAN_WRITE_OFF_RESERVE', 9970473
  UNION ALL SELECT 2026, 'OTHER_LOANS', 28109000
  UNION ALL SELECT 2026, 'FIXED_ASSETS', 1
  UNION ALL SELECT 2026, 'DEBT_PPBRI', 10000000
  UNION ALL SELECT 2026, 'NON_MEMBER_SAVINGS', 876000
  UNION ALL SELECT 2026, 'CAPITAL_RESERVE', 42991150
  UNION ALL SELECT 2026, 'EDUCATION_FUND', 3460622
  UNION ALL SELECT 2026, 'SOCIAL_FUND', 1232995
  UNION ALL SELECT 2026, 'PMDK_FUND', 3494387
  UNION ALL SELECT 2026, 'LOAN_WRITE_OFF_RESERVE', 9970473
  UNION ALL SELECT 2026, 'RETAINED_EARNINGS', 7591369
)
WHERE id = 'default';
